static const char saturnQuadVertex[] =
    "layout(location=0) in ivec2 rowInfo;\n"
    "layout(std140) uniform QuadCommands { vec4 commands[1008]; };\n"
    "uniform vec4 effect[8];\n"
    "#define target effect[0].xy\n"
    "#define origin effect[0].zw\n"
    "#define clipBounds ivec4(effect[1])\n"
    "flat out ivec4 line, props, tex, win, info;\n"
    "flat out vec4 uvAB, uvCD, zAlpha, palette0, palette1, palette2, palette3;\n"
    "flat out vec3 shadeL, shadeR;\n"
    "out vec3 trackUVAlpha;\n"
    "vec4 data(int i) { return commands[rowInfo.x*18+i]; }\n"
    "void main() {\n"
    "    props=ivec4(data(14)); tex=ivec4(data(15)); win=ivec4(data(16)); info=ivec4(data(17));\n"
    "    info.w=(rowInfo.x<<1)|info.w;\n"
    "    palette0=data(10);palette1=data(11);palette2=data(12);palette3=data(13);\n"
    "    vec4 ab=data(1),cd=data(2),zs=data(3),as=data(4);\n"
    "    vec4 uvab=data(5),uvcd=data(6);\n"
    "    if(props.w>=2) {\n"
    "        const int quadCorners[6]=int[6](0,1,3,1,3,2);\n"
    "        int k=props.w==2 ? quadCorners[gl_VertexID] : (gl_VertexID<3 ? gl_VertexID : 0);\n"
    "        vec4 pair=k<2 ? ab : cd, uv=k<2 ? uvab : uvcd;\n"
    "        vec2 p=(k&1)==0 ? pair.xy : pair.zw;\n"
    "        trackUVAlpha=vec3((k&1)==0 ? uv.xy : uv.zw,as[k]);\n"
    "        float w=zs[k]>0.0 ? 1.0/zs[k] : 1.0;\n"
    "        gl_Position=vec4(((p-origin)/target*2.0-1.0)*w,w-2.0,w);\n"
    "        return;\n"
    "    }\n"
    "    vec4 red=data(7),green=data(8),blue=data(9);\n"
    "    float t=info.x>0 ? float(rowInfo.y)/float(info.x) : 0.0;\n"
    "    info.y=rowInfo.y;\n"
    "    vec2 a=floor(ab.xy+(cd.zw-ab.xy)*t+0.5);\n"
    "    vec2 b=floor(ab.zw+(cd.xy-ab.zw)*t+0.5);\n"
    "    line=ivec4(a,b);\n"
    "    uvAB=uvab; uvCD=uvcd;\n"
    "    shadeL=vec3(red.x,green.x,blue.x)*(1.0-t)+vec3(red.w,green.w,blue.w)*t;\n"
    "    shadeR=vec3(red.y,green.y,blue.y)*(1.0-t)+vec3(red.z,green.z,blue.z)*t;\n"
    "    zAlpha=vec4(zs.xy*(1.0-t)+zs.wz*t,as.xy*(1.0-t)+as.wz*t);\n"
    "    vec2 corner=vec2((gl_VertexID==1 || gl_VertexID==2 || gl_VertexID==4)?1:0,\n"
    "                     (gl_VertexID==2 || gl_VertexID==4 || gl_VertexID==5)?1:0);\n"
    "    vec2 p;\n"
    "    if(props.w!=0) {\n"
    "        vec4 bounds=data(0);\n"
    "        p=mix(max(bounds.xy,vec2(clipBounds.xy)),min(bounds.zw,vec2(clipBounds.zw)),corner);\n"
    "    } else {\n"
    "        // A narrow strip covers the DDA pixels and diagonal connecting pixels.\n"
    "        // Fragment coverage decides the exact integer pixels, not triangle interpolation.\n"
    "        vec2 dir=b-a;\n"
    "        dir=length(dir)>0.0 ? normalize(dir) : vec2(1,0);\n"
    "        vec2 normal=vec2(-dir.y,dir.x);\n"
    "        p=mix(a-dir*2.0,b+dir*2.0,corner.x)+normal*(corner.y*4.0-2.0)+vec2(0.5);\n"
    "        if(any(lessThan(max(a,b),vec2(clipBounds.xy))) || any(greaterThanEqual(min(a,b),vec2(clipBounds.zw))))\n"
    "            p=vec2(clipBounds.xy)-vec2(100);\n"
    "    }\n"
    "    gl_Position=vec4((p-origin)/target*2.0-1.0,0,1);\n"
    "}\n"
;

static const char saturnQuadFragment[] =
    "#ifdef GL_ES\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "precision highp usampler2D;\n"
    "#endif\n"
    "layout(std140) uniform QuadCommands { vec4 commands[1008]; };\n"
    "uniform usampler2D image0, image1;\n"
    "uniform vec4 effect[8];\n"
    "#define vram image0\n"
    "#define sourcePixels image1\n"
    "#define origin effect[0].zw\n"
    "#define renderScale effect[2].x\n"
    "flat in ivec4 line, props, tex, win, info;\n"
    "flat in vec4 uvAB, uvCD, zAlpha, palette0, palette1, palette2, palette3;\n"
    "flat in vec3 shadeL, shadeR;\n"
    "in vec3 trackUVAlpha;\n"
    "out vec4 result;\n"
    "vec4 data(int i) { return commands[(info.w>>1)*18+i]; }\n"
    "int indexAt(vec2 uv, out int identity) {\n"
    "    ivec2 at=ivec2(floor(uv+vec2(0.00001)));\n"
    "    if(tex.z>0) {\n"
    "        at=clamp(at,ivec2(0),tex.zw-1); identity=at.x;\n"
    "        return int(texelFetch(sourcePixels,tex.xy+at,0).r);\n"
    "    }\n"
    "    identity=at.x+256*at.y;\n"
    "    at &= ivec2(255);\n"
    "    ivec2 masks=ivec2(win.z&255,(win.z>>8)&255)*8;\n"
    "    ivec2 offsets=ivec2(win.w&255,(win.w>>8)&255)*8;\n"
    "    at=(at & ~masks) | (offsets & masks);\n"
    "    uint packed=texelFetch(vram,ivec2((win.x+at.x/4)&1023,(win.y+at.y)&1023),0).r;\n"
    "    return int((packed>>uint((at.x&3)*4))&15u);\n"
    "}\n"
    "vec2 uvAt(int col,int steps) {\n"
    "    if(tex.z>0 && info.z==0)\n"
    "        return vec2(col*tex.z/(steps+1),info.y*tex.w/(info.x+1));\n"
    "    float s=steps>0 ? float(col)/float(steps) : 0.0;\n"
    "    float t=info.x>0 ? float(info.y)/float(info.x) : 0.0;\n"
    "    return (uvAB.xy*(1.0-s)+uvAB.zw*s)*(1.0-t)+(uvCD.zw*(1.0-s)+uvCD.xy*s)*t;\n"
    "}\n"
    "int roundedProduct(int n,int minor,int major) {\n"
    "    if(major==0) return 0;\n"
    "    // Small coordinates use the same integer division as the reference.\n"
    "    if(n<=32767 && minor<=32767) return (n*minor+major/2)/major;\n"
    "    return int(floor((float(n)*float(minor)+float(major/2))/float(major)));\n"
    "}\n"
    "void main() {\n"
    "    ivec2 pixel=ivec2(floor(gl_FragCoord.xy)+origin);\n"
    "    bool alphaMesh=(props.x&65536)!=0;\n"
    "    if((props.x&256)!=0 && !alphaMesh) {\n"
    "        ivec2 dot=ivec2(floor(vec2(pixel)/renderScale));\n"
    "        if(((dot.x+dot.y)&1)!=0) discard;\n"
    "    }\n"
    "    vec2 uv; vec3 shade; float depth,alpha;\n"
    "    int col=0,steps=0;\n"
    "    if(props.w>=2) {\n"
    "        uv=trackUVAlpha.xy; alpha=trackUVAlpha.z;\n"
    "        shade=vec3(16.0); depth=1.0-gl_FragCoord.z;\n"
    "    } else if(props.w!=0) {\n"
    "        vec4 ab=data(1),cd=data(2);\n"
    "        vec2 e=ab.zw-ab.xy,f=cd.xy-ab.xy,p=vec2(pixel)-ab.xy;\n"
    "        float det=e.x*f.y-e.y*f.x;\n"
    "        if(abs(det)<0.00001) discard;\n"
    "        vec3 weights;\n"
    "        weights.y=(p.x*f.y-p.y*f.x)/det;\n"
    "        weights.z=(e.x*p.y-e.y*p.x)/det;\n"
    "        weights.x=1.0-weights.y-weights.z;\n"
    "        if(any(lessThan(weights,vec3(-0.000001)))) discard;\n"
    "        vec4 uvs=data(5),other=data(6);\n"
    "        uv=uvs.xy*weights.x+uvs.zw*weights.y+other.xy*weights.z;\n"
    "        shade=vec3(dot(data(7).xyz,weights),dot(data(8).xyz,weights),dot(data(9).xyz,weights));\n"
    "        depth=dot(data(3).xyz,weights); alpha=dot(data(4).xyz,weights);\n"
    "    } else {\n"
    "        ivec2 delta=abs(line.zw-line.xy),signs=ivec2(line.x<line.z?1:-1,line.y<line.w?1:-1);\n"
    "        steps=max(delta.x,delta.y);\n"
    "        bool xMajor=delta.x>=delta.y;\n"
    "        col=xMajor ? (pixel.x-line.x)*signs.x : (pixel.y-line.y)*signs.y;\n"
    "        if(col<0 || col>steps) discard;\n"
    "        ivec2 at=line.xy+signs*ivec2(xMajor?col:roundedProduct(col,delta.x,delta.y),\n"
    "                                    xMajor?roundedProduct(col,delta.y,delta.x):col);\n"
    "        if(any(notEqual(at,pixel))) {\n"
    "            if(xMajor) {\n"
    "                if(col==0 || pixel.y!=line.y+signs.y*roundedProduct(col-1,delta.y,delta.x) || pixel.y==at.y) discard;\n"
    "                col--; // connecting pixel belongs to the preceding source sample\n"
    "            } else {\n"
    "                if(col==steps || pixel.x!=line.x+signs.x*roundedProduct(col+1,delta.x,delta.y) || pixel.x==at.x) discard;\n"
    "            }\n"
    "        }\n"
    "        float s=steps>0 ? float(col)/float(steps) : 0.0;\n"
    "        uv=uvAt(col,steps);\n"
    "        shade=shadeL*(1.0-s)+shadeR*s;\n"
    "        depth=zAlpha.x*(1.0-s)+zAlpha.y*s;\n"
    "        alpha=zAlpha.z*(1.0-s)+zAlpha.w*s;\n"
    "    }\n"
    "    int colour=props.y;\n"
    "    if(props.z!=0) {\n"
    "        int identity;int index=indexAt(uv,identity);\n"
    "        if((props.x&128)==0) {\n"
    "            if(index==15) discard;\n"
    "            // Rare end-code commands terminate at the second distinct source read.\n"
    "            // Scan on the GPU, including samples clipped off the display.\n"
    "            if(props.w==0) {\n"
    "                int ends=0,previous=-1;\n"
    "                for(int c=0;c<=col;c++) {\n"
    "                    int id;int sampleIndex=indexAt(uvAt(c,steps),id);\n"
    "                    if(sampleIndex==15 && id!=previous && ++ends==2) discard;\n"
    "                    previous=id;\n"
    "                }\n"
    "            }\n"
    "        }\n"
    "        if(index==0 && (props.x&64)==0) discard;\n"
    "        vec4 pal=index<4?palette0:index<8?palette1:index<12?palette2:palette3;\n"
    "        colour=int(pal[index&3]);\n"
    "    }\n"
    "    ivec3 rgb=ivec3(colour&31,(colour>>5)&31,(colour>>10)&31);\n"
    "    if((props.x&4)!=0) rgb=clamp(rgb+ivec3(floor(shade+vec3(0.00001)))-16,ivec3(0),ivec3(31));\n"
    "    int operation=props.x&3;\n"
    "    if(operation==2) rgb >>= 1;\n"
    "    if(operation==1) rgb=ivec3(0);\n"
    "    float a=floor(clamp(alpha,0.0,255.0)+0.5)/255.0;\n"
    "    if(alphaMesh) a*=0.5;\n"
    "    if(operation==1 || operation==3) a*=0.5;\n"
    "    result=vec4(vec3(rgb)*(8.0/255.0)*a,a);\n"
    "    gl_FragDepth=(info.w&1)==0 && depth>0.0 ? clamp(1.0-depth,0.0,1.0) : 0.0;\n"
    "}\n"
;


#!/usr/bin/env python3
"""Regenerate the Modern postprocessing fragments using glslang and SPIRV-Cross."""

import ast
import sys
from pathlib import Path
import re
import subprocess
import tempfile

RENDER = Path(__file__).resolve().parents[1] / "platform" / "render"
FRAGMENTS = ("modernMotionFragment", "modernResolveFragment")
MARKER = "\n/* Modern postprocessing */"
HELPERS = (
    "LinearColour", "Srgb", "Score", "Scene", "Peak", "Seed", "ToneMap",
    "ToneMapPbrNeutral", "Field", "InPicture", "SweepCoverage", "MotionColour",
)


def metal_fragment(header, name, directory):
    strings = re.search(rf"static const char {name}\[\] =\n(.*?)\n;", header, re.S)[1]
    glsl = "".join(ast.literal_eval(line.strip()) for line in strings.splitlines())
    glsl = re.sub(r"#ifdef GL_ES\n.*?#endif\n", "", glsl, flags=re.S)
    glsl = re.sub(
        r"uniform sampler2D image(\d);",
        r"layout(set=0,binding=\1) uniform sampler2D image\1;",
        glsl,
    )
    glsl = glsl.replace(
        "uniform vec4 effect[8];",
        f"layout(std140,set=1,binding=3) uniform {name}Uniforms {{ vec4 effect[8]; }};",
    )
    glsl = glsl.replace("out vec4 motion;", "layout(location=0) out vec4 motion;")
    fragment, binary = directory / f"{name}.frag", directory / f"{name}.spv"
    defines = "#define PREPARE_LINEAR_SCENE 1\n" if name == "modernResolveFragment" else ""
    fragment.write_text("#version 450\n" + defines + glsl)
    subprocess.run(["glslangValidator", "-V", str(fragment), "-o", str(binary)], check=True)
    msl = subprocess.check_output(
        ["spirv-cross", str(binary), "--msl", "--msl-version", "20300", "--msl-decoration-binding",
         "--rename-entry-point", "main", name, "frag"], text=True,
    )
    msl = msl[msl.index("struct "):].replace("[[buffer(0)]]", "[[buffer(3)]]")
    if name == "modernMotionFragment":
        msl = msl.replace("texture2d<float> image1", "depth2d<float> image1")
        msl = re.sub(r"(image1\.read\(.*\))\.x", r"\1", msl)
    return re.sub(r"\b(" + "|".join(HELPERS) + r")\(", rf"{name}_\1(", msl)


def main():
    header = (RENDER / "modern" / "portable_post.h").read_text()
    with tempfile.TemporaryDirectory() as temp:
        fragments = [metal_fragment(header, name, Path(temp)) for name in FRAGMENTS]
    path = RENDER / "shaders_metal.metal"
    handwritten = path.read_text().split(MARKER, 1)[0].rstrip()
    generated = (handwritten + "\n" + MARKER +
                    "\n/* Generated by tools/generate_modern_metal.py. */\n" +
                    "\n".join(fragments).rstrip() + "\n")
    if "--check" in sys.argv:
        if path.read_text() != generated:
            raise SystemExit("Modern Metal shader drift; run tools/generate_modern_metal.py")
    else:
        path.write_text(generated)


if __name__ == "__main__":
    main()
